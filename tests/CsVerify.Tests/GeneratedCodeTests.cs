using System;
using System.IO;
using System.Linq;
using CsVerify.Verifier;
using Xunit;

namespace CsVerify.Tests
{
    /// <summary>
    /// Generated code (#41): the SDK's files under obj/ (global usings) and source generators' output are compiled
    /// with the program, not verified; the project's generators run in the verifier and in erasure.
    /// </summary>
    public class GeneratedCodeTests
    {
        private const string Uses = @"using CsVerify;
public static partial class Codes
{
    public static int Count(List<int> xs) => xs.Count;
    public static int Inc(int x) { Spec.Requires(x < 10); Spec.Ensures<int>(r => r == x + 1); return x + 1; }
}";

        [Fact]
        public void AGeneratedFile_IsCompiled_NotVerified()
        {
            // (a global using, as the SDK's GlobalUsings.g.cs has it, and a generated method that fails its postcondition)
            var r = Engine.VerifySources(new[]
            {
                ("Codes.cs", Uses),
                ("obj/Debug/net10.0/App.GlobalUsings.g.cs", "global using System.Collections.Generic;"),
                ("Gen.cs", "// <auto-generated/>\npublic static class Gen { public static int Wrong(int x) { CsVerify.Spec.Ensures<int>(r => r > x); return x; } }"),
            }, new VerifierOptions());
            Assert.Empty(r.CompilationErrors);
            Assert.Empty(r.Errors("Inc"));
            Assert.DoesNotContain(r.Methods, m => m.Name.Contains("Wrong"));
        }

        /// <summary>The regex source generator of the targeting pack the tests run on.</summary>
        private static string RegexGenerator()
        {
            var dotnet = Path.GetFullPath(Path.Combine(Path.GetDirectoryName(typeof(object).Assembly.Location)!, "..", "..", ".."));
            var packs = Path.Combine(dotnet, "packs", "Microsoft.NETCore.App.Ref");
            var major = Environment.Version.Major + ".";
            return Directory.Exists(packs)
                ? Directory.GetDirectories(packs).Where(d => Path.GetFileName(d).StartsWith(major)).OrderByDescending(d => d, StringComparer.Ordinal)
                    .Select(d => Path.Combine(d, "analyzers", "dotnet", "cs", "System.Text.RegularExpressions.Generator.dll")).FirstOrDefault(File.Exists)
                : null;
        }

        private const string Regex = @"using System.Text.RegularExpressions;
using CsVerify;
public static partial class Codes
{
    [GeneratedRegex(""^[A-Z]{3}$"")]
    public static partial Regex ThreeLetters();
    public static int Inc(int x) { Spec.Requires(x < 10); Spec.Ensures<int>(r => r == x + 1); return x + 1; }
}";

        [Fact]
        public void TheProjectsSourceGenerators_RunInTheVerifier()
        {
            var generator = RegexGenerator();
            Assert.True(generator != null, "no regex generator in the targeting pack");
            var options = new VerifierOptions();
            options.Analyzers.Add(generator);
            var r = Engine.VerifySources(new[] { ("Codes.cs", Regex) }, options);
            Assert.Empty(r.CompilationErrors);
            Assert.Empty(r.Errors("Inc"));
            // (without it, the partial method has no implementation)
            Assert.Contains(Engine.VerifySources(new[] { ("Codes.cs", Regex) }, new VerifierOptions()).CompilationErrors, d => d.Id == "CS8795");
        }

        [Fact]
        public void TheProjectsSourceGenerators_RunInErasure()
        {
            var generator = RegexGenerator();
            Assert.True(generator != null, "no regex generator in the targeting pack");
            var erased = Erasure.Erase(new[] { ("Codes.cs", Regex) }, Array.Empty<string>(), Array.Empty<string>(), analyzers: new[] { generator });
            Assert.True(erased.Success, string.Join("\n", erased.Errors));
            // (what they generate isn't written: the compiler generates it again)
            Assert.Single(erased.Files, f => f.OriginalPath == "Codes.cs");
            Assert.DoesNotContain(erased.Files, f => f.OutputName.Contains("RegexGenerator"));
        }
    }
}
