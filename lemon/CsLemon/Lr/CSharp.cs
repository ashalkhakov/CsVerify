// The C# back end (-C): instead of grammar.c and grammar.h from lempar.c, a grammar.cs whose parser is the verified LR
// interpreter of CsLemon.Runtime running the automaton CsLemon built, once it passes the safety validator. The
// grammar's actions are C# here: each rule's code becomes a case of Reduce, with its aliases as variables.
using System.Text;
using CsVerify;

namespace CsLemon.Lr
{
    public static class CSharp
    {
        /// <summary>The value type of a symbol: %type for a nonterminal (or %default_type), %token_type for terminals.</summary>
        private static string TypeOf(Lemon lemp, Symbol sp)
        {
            string? t = sp.type == SymbolType.NONTERMINAL ? sp.datatype ?? lemp.vartype : lemp.tokentype;
            return t != null && t.Trim().Length > 0 ? t.Trim() : "object?";
        }

        /// <summary>The name declared last in a parameter declaration ("Ctx ctx" gives ctx).</summary>
        private static string ParamName(string decl)
        {
            string d = decl.Trim();
            int end = d.Length;
            int start = end;
            while (start > 0 && (char.IsLetterOrDigit(d[start - 1]) || d[start - 1] == '_'))
            {
                Spec.Invariant(0 <= start && start <= d.Length);
                start--;
            }
            return d.Substring(start, end - start);
        }

        private static void Ints(StringBuilder sb, int[]? xs)
        {
            sb.Append("new int[] {");
            if (xs != null)
                for (int i = 0; i < xs.Length; i++)
                {
                    Spec.Invariant(0 <= i);
                    sb.Append(i == 0 ? " " : ", ").Append(xs[i]);
                }
            sb.Append(" }");
        }

        private static void Rows(StringBuilder sb, int[][] rows, string indent)
        {
            sb.Append("new int[][] {\n");
            for (int i = 0; i < rows.Length; i++)
            {
                Spec.Invariant(0 <= i);
                sb.Append(indent).Append("    ");
                Ints(sb, rows[i]);
                sb.Append(",\n");
            }
            sb.Append(indent).Append('}');
        }

        /// <summary>Writes the C# parser; false (and a message) if the automaton does not pass the safety validator.</summary>
        public static bool Write(Lemon lemp, string path)
        {
            var g = Export.GrammarOf(lemp, out int[] incoming, out int[][] syms);
            var a = Export.AutomatonOf(lemp, incoming);
            if (!Safety.Validate(g, a, Export.AnnotationsOf(g, a, syms)))
            {
                System.Console.Error.Write(lemp.filename + ": the automaton does not pass the safety validator; no C# parser written.\n");
                return false;
            }
            bool complete = Completeness.Validate(g, a, Export.ItemsOf(lemp, g, a));
            var sb = new StringBuilder();
            Header(sb, lemp, complete);
            Tokens(sb, lemp);
            Tables(sb, g, a);
            EntryPoints(sb, lemp);
            sb.Append("    private static object? Reduce(int yyrule, object?[] k").Append(ArgDecl(lemp)).Append(")\n    {\n        switch (yyrule)\n        {\n");
            for (Rule? rp = lemp.rule; rp != null; rp = rp.next) ActionCase(sb, lemp, rp);
            sb.Append("        }\n        return null;\n    }\n");
            if (lemp.extracode != null) sb.Append('\n').Append(lemp.extracode).Append('\n');
            sb.Append("}\n");
            System.IO.File.WriteAllText(path, sb.ToString(), Encoding.Latin1);
            return true;
        }

        /// <summary>The extra argument's declaration (%extra_argument), or null.</summary>
        private static string? Arg(Lemon lemp) => lemp.arg != null && lemp.arg.Trim().Length > 0 ? lemp.arg.Trim() : null;

        /// <summary>", Ctx ctx" after other parameters, or nothing.</summary>
        private static string ArgDecl(Lemon lemp) => Arg(lemp) is string arg ? ", " + arg : "";

        /// <summary>", ctx" after other arguments, or nothing.</summary>
        private static string ArgPass(Lemon lemp) => Arg(lemp) is string arg ? ", " + ParamName(arg) : "";

        private static void Header(StringBuilder sb, Lemon lemp, bool complete)
        {
            sb.Append("// Generated by cslemon -C from ").Append(lemp.filename).Append(". The parser is CsLemon.Lr's verified LR interpreter\n");
            sb.Append("// running the automaton below, which passed the safety validator (the interpreter reaches no internal error)");
            sb.Append(complete ? "\n// and the completeness validator (every sentence is parsed, into its one parse tree).\n"
                               : ".\n// (Not the completeness validator: the grammar's conflicts were resolved by precedence, or remain.)\n");
            sb.Append("#nullable enable\n#pragma warning disable\n");
            if (lemp.include != null) sb.Append(lemp.include).Append('\n');
            sb.Append("using CsLemon.Lr;\n\n");
            sb.Append("public static partial class ").Append(lemp.name ?? "Parse").Append("Parser\n{\n");
        }

        /// <summary>The token codes, as Lemon's grammar.h has them.</summary>
        private static void Tokens(StringBuilder sb, Lemon lemp)
        {
            for (int i = 1; i < lemp.nterminal; i++)
            {
                Spec.Invariant(1 <= i);
                Symbol sp = lemp.Sym(i);
                sb.Append("    public const int ").Append(lemp.tokenprefix ?? "").Append(sp.name).Append(" = ").Append(i).Append(";\n");
            }
        }

        private static void Tables(StringBuilder sb, Grammar g, Automaton a)
        {
            sb.Append("\n    private static readonly Grammar G = new Grammar(").Append(g.NTerm).Append(", ").Append(g.NSym).Append(", ").Append(g.Start).Append(",\n        ");
            Ints(sb, g.Lhs);
            sb.Append(",\n        ");
            Rows(sb, g.Rhs, "        ");
            sb.Append(",\n        ");
            Rows(sb, g.Multi, "        ");
            sb.Append(");\n\n    private static readonly Automaton A = new Automaton(").Append(a.NState).Append(",\n        ");
            Ints(sb, a.Incoming);
            sb.Append(",\n        ");
            Rows(sb, a.Kind, "        ");
            sb.Append(",\n        ");
            Rows(sb, a.Arg, "        ");
            sb.Append(",\n        ");
            Rows(sb, a.Goto, "        ");
            sb.Append(");\n\n");
        }

        private static void EntryPoints(StringBuilder sb, Lemon lemp)
        {
            string argDecl = ArgDecl(lemp), argPass = ArgPass(lemp);
            string argOnly = Arg(lemp) ?? "", argOnlyPass = Arg(lemp) is string arg ? ParamName(arg) : "";
            sb.Append("    /// <summary>The input's parse tree, by the verified interpreter.</summary>\n");
            sb.Append("    public static Result ParseTree(int[] tokens) => Interpreter.Parse(G, A, tokens, int.MaxValue, default);\n\n");
            sb.Append("    /// <summary>Parses the tokens (whose values are given alongside), running the rules' actions; whether the input is a sentence.</summary>\n");
            sb.Append("    public static bool Parse(int[] tokens, object?[] values").Append(argDecl).Append(")\n    {\n");
            sb.Append("        Result r = ParseTree(tokens);\n");
            sb.Append("        if (r is Result.Accepted acc && acc.Consumed == tokens.Length)\n        {\n");
            sb.Append("            Evaluator.Evaluate(acc.T, values, (rule, k) => Reduce(rule, k").Append(argPass).Append("));\n");
            sb.Append("            Accept(").Append(argOnlyPass).Append(");\n            return true;\n        }\n");
            sb.Append("        int at = tokens.Length;\n");
            sb.Append("        if (r is Result.Rejected rej)\n        {\n");
            sb.Append("            /* the actions of the reductions made before the error, as a parser running them as it reduces has run them */\n");
            sb.Append("            Evaluator.EvaluateStack(rej.S, values, (rule, k) => Reduce(rule, k").Append(argPass).Append("));\n");
            sb.Append("            at = rej.At;\n        }\n");
            sb.Append("        SyntaxError(at < tokens.Length ? tokens[at] : 0, at < values.Length ? values[at] : null").Append(argPass).Append(");\n");
            sb.Append("        Failure(").Append(argOnlyPass).Append(");\n        return false;\n    }\n\n");
            sb.Append("    private static void SyntaxError(int yymajor, object? TOKEN").Append(argDecl).Append(")\n    {\n").Append(lemp.error ?? "").Append("\n    }\n\n");
            sb.Append("    private static void Accept(").Append(argOnly).Append(")\n    {\n").Append(lemp.accept ?? "").Append("\n    }\n\n");
            sb.Append("    private static void Failure(").Append(argOnly).Append(")\n    {\n").Append(lemp.failure ?? "").Append("\n    }\n\n");
        }

        /// <summary>A rule's action: its aliases as variables of their symbols' types, its code, and the left-hand side's value.</summary>
        private static void ActionCase(StringBuilder sb, Lemon lemp, Rule rp)
        {
            sb.Append("            case ").Append(rp.index).Append(": /* ").Append(rp.lhs.name).Append(" ::=");
            for (int i = 0; i < rp.nrhs; i++)
            {
                Spec.Invariant(0 <= i);
                Symbol s = rp.Rhs(i);
                sb.Append(' ').Append(s.type == SymbolType.MULTITERMINAL ? MultiName(s) : s.name);
            }
            sb.Append(" */\n            {\n");
            bool lhsIsRhs = false;
            for (int i = 0; i < rp.nrhs && i < rp.rhsalias.Length; i++)
            {
                Spec.Invariant(0 <= i);
                string? alias = rp.rhsalias[i];
                if (alias == null) continue;
                if (alias == rp.lhsalias) lhsIsRhs = true;
                string t = TypeOf(lemp, rp.Rhs(i));
                sb.Append("                ").Append(t).Append(' ').Append(alias).Append(" = (").Append(t).Append(")k[").Append(i).Append("]!;\n");
            }
            if (rp.lhsalias != null && !lhsIsRhs)
                sb.Append("                ").Append(TypeOf(lemp, rp.lhs)).Append(' ').Append(rp.lhsalias).Append(" = default!;\n");
            if (rp.code != null) sb.Append("                {").Append(rp.code).Append("}\n");
            if (rp.lhsalias != null) sb.Append("                return ").Append(rp.lhsalias).Append(";\n");
            else if (rp.code == null) sb.Append("                return k.Length > 0 ? k[0] : null;\n");
            else sb.Append("                return null;\n");
            sb.Append("            }\n");
        }

        private static string MultiName(Symbol sp)
        {
            var sb = new StringBuilder();
            for (int k = 0; k < sp.nsubsym; k++)
            {
                Spec.Invariant(0 <= k);
                sb.Append(k == 0 ? "" : "|").Append(sp.Sub(k).name);
            }
            return sb.ToString();
        }
    }
}
