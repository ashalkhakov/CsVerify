// Routines to construction the finite state machine for the LEMON parser generator (build.c).
namespace CsLemon
{
    public static class Build
    {
        /* Find a precedence symbol of every rule in the grammar.
        **
        ** Those rules which have a precedence symbol coded in the input grammar using the "[symbol]" construct will
        ** already have the rp->precsym field filled.  Other rules take as their precedence symbol the first RHS
        ** symbol with a defined precedence.  If there are not RHS symbols with a defined precedence, the precedence
        ** symbol field is left blank.
        */
        public static void FindRulePrecedences(Lemon xp)
        {
            Rule? rp;
            for (rp = xp.rule; rp != null; rp = rp.next)
            {
                if (rp.precsym == null)
                {
                    int i, j;
                    for (i = 0; i < rp.nrhs && rp.precsym == null; i++)
                    {
                        Symbol sp = rp.rhs[i];
                        if (sp.type == SymbolType.MULTITERMINAL)
                        {
                            for (j = 0; j < sp.nsubsym; j++)
                            {
                                if (sp.subsym![j].prec >= 0)
                                {
                                    rp.precsym = sp.subsym[j];
                                    break;
                                }
                            }
                        }
                        else if (sp.prec >= 0)
                        {
                            rp.precsym = rp.rhs[i];
                        }
                    }
                }
            }
        }

        /* Find all nonterminals which will generate the empty string.  Then go back and compute the first sets of
        ** every nonterminal.  The first set is the set of all terminal symbols which can begin a string generated by
        ** that nonterminal.
        */
        public static void FindFirstSets(Lemon lemp)
        {
            int i, j;
            Rule? rp;
            bool progress;

            for (i = 0; i < lemp.nsymbol; i++)
            {
                lemp.symbols[i].lambda = false;
            }
            for (i = lemp.nterminal; i < lemp.nsymbol; i++)
            {
                lemp.symbols[i].firstset = Sets.SetNew();
            }

            /* First compute all lambdas */
            do
            {
                progress = false;
                for (rp = lemp.rule; rp != null; rp = rp.next)
                {
                    if (rp.lhs.lambda) continue;
                    for (i = 0; i < rp.nrhs; i++)
                    {
                        Symbol sp = rp.rhs[i];
                        System.Diagnostics.Debug.Assert(sp.type == SymbolType.NONTERMINAL || sp.lambda == false);
                        if (sp.lambda == false) break;
                    }
                    if (i == rp.nrhs)
                    {
                        rp.lhs.lambda = true;
                        progress = true;
                    }
                }
            } while (progress);

            /* Now compute all first sets */
            do
            {
                Symbol s1, s2;
                progress = false;
                for (rp = lemp.rule; rp != null; rp = rp.next)
                {
                    s1 = rp.lhs;
                    for (i = 0; i < rp.nrhs; i++)
                    {
                        s2 = rp.rhs[i];
                        if (s2.type == SymbolType.TERMINAL)
                        {
                            if (Sets.SetAdd(s1.firstset!, s2.index)) progress = true;
                            break;
                        }
                        else if (s2.type == SymbolType.MULTITERMINAL)
                        {
                            for (j = 0; j < s2.nsubsym; j++)
                            {
                                if (Sets.SetAdd(s1.firstset!, s2.subsym![j].index)) progress = true;
                            }
                            break;
                        }
                        else if (s1 == s2)
                        {
                            if (s1.lambda == false) break;
                        }
                        else
                        {
                            if (Sets.SetUnion(s1.firstset!, s2.firstset!)) progress = true;
                            if (s2.lambda == false) break;
                        }
                    }
                }
            } while (progress);
        }

        /* Compute all LR(0) states for the grammar.  Links are added to between some states so that the LR(1)
        ** follow sets can be computed later.
        */
        public static void FindStates(Lemon lemp)
        {
            Symbol? sp;
            Rule? rp;

            ConfigList.Configlist_init();

            /* Find the start symbol */
            if (lemp.start != null)
            {
                sp = Tables.Symbol_find(lemp.start);
                if (sp == null)
                {
                    Errors.ErrorMsg(lemp.filename, 0,
                      "The specified start symbol \"" + lemp.start + "\" is not " +
                      "in a nonterminal of the grammar.  \"" + lemp.startRule!.lhs.name + "\" will be used as the start " +
                      "symbol instead.");
                    lemp.errorcnt++;
                    sp = lemp.startRule.lhs;
                }
            }
            else if (lemp.startRule != null)
            {
                sp = lemp.startRule.lhs;
            }
            else
            {
                Errors.ErrorMsg(lemp.filename, 0, "Internal error - no start rule\n");
                System.Environment.Exit(1);
                return;
            }

            /* Make sure the start symbol doesn't occur on the right-hand side of any rule.  Report an error if it
            ** does.  (YACC would generate a new start symbol in this case.) */
            for (rp = lemp.rule; rp != null; rp = rp.next)
            {
                int i;
                for (i = 0; i < rp.nrhs; i++)
                {
                    if (rp.rhs[i] == sp)
                    {   /* FIX ME:  Deal with multiterminals */
                        Errors.ErrorMsg(lemp.filename, 0,
                          "The start symbol \"" + sp.name + "\" occurs on the " +
                          "right-hand side of a rule. This will result in a parser which " +
                          "does not work properly.");
                        lemp.errorcnt++;
                    }
                }
            }

            /* The basis configuration set for the first state is all rules which have the start symbol as their
            ** left-hand side */
            for (rp = sp.rule; rp != null; rp = rp.nextlhs)
            {
                Config newcfp;
                rp.lhsStart = true;
                newcfp = ConfigList.Configlist_addbasis(rp, 0);
                Sets.SetAdd(newcfp.fws!, 0);
            }

            /* Compute the first state.  All other states will be computed automatically during the computation of
            ** the first one.  The returned pointer to the first state is not used. */
            getstate(lemp);
        }

        /* Return a pointer to a state which is described by the configuration list which has been built from calls
        ** to Configlist_add.
        */
        private static State getstate(Lemon lemp)
        {
            Config? cfp, bp;
            State? stp;

            /* Extract the sorted basis of the new state.  The basis was constructed by prior calls to
            ** "Configlist_addbasis()". */
            ConfigList.Configlist_sortbasis();
            bp = ConfigList.Configlist_basis();

            /* Get a state with the same basis */
            stp = Tables.State_find(bp);
            if (stp != null)
            {
                /* A state with the same basis already exists!  Copy all the follow-set propagation links from the
                ** state under construction into the preexisting state, then return a pointer to the preexisting
                ** state */
                Config? x, y;
                for (x = bp, y = stp.bp; x != null && y != null; x = x.bp, y = y.bp)
                {
                    y.bplp = Plinks.Plink_copy(y.bplp, x.bplp);
                    Plinks.Plink_delete(x.fplp);
                    x.fplp = null;
                    x.bplp = null;
                }
                cfp = ConfigList.Configlist_return();
                ConfigList.Configlist_eat(cfp);
            }
            else
            {
                /* This really is a new state.  Construct all the details */
                ConfigList.Configlist_closure(lemp);    /* Compute the configuration closure */
                ConfigList.Configlist_sort();           /* Sort the configuration closure */
                cfp = ConfigList.Configlist_return();   /* Get a pointer to the config list */
                stp = new State();                      /* A new state structure */
                stp.bp = bp;                            /* Remember the configuration basis */
                stp.cfp = cfp;                          /* Remember the configuration closure */
                stp.statenum = lemp.nstate++;           /* Every state gets a sequence number */
                stp.ap = null;                          /* No actions, yet. */
                Tables.State_insert(stp, stp.bp);       /* Add to the state table */
                buildshifts(lemp, stp);                 /* Recursively compute successor states */
            }
            return stp;
        }

        /*
        ** Return true if two symbols are the same.
        */
        private static bool same_symbol(Symbol a, Symbol b)
        {
            int i;
            if (a == b) return true;
            if (a.type != SymbolType.MULTITERMINAL) return false;
            if (b.type != SymbolType.MULTITERMINAL) return false;
            if (a.nsubsym != b.nsubsym) return false;
            for (i = 0; i < a.nsubsym; i++)
            {
                if (a.subsym![i] != b.subsym![i]) return false;
            }
            return true;
        }

        /* Construct all successor states to the given state.  A "successor" state is any state which can be reached
        ** by a shift action.
        */
        private static void buildshifts(Lemon lemp, State stp)
        {
            Config? cfp;     /* For looping thru the config closure of "stp" */
            Config? bcfp;    /* For the inner loop on config closure of "stp" */
            Config newcfg;   /* */
            Symbol sp;       /* Symbol following the dot in configuration "cfp" */
            Symbol bsp;      /* Symbol following the dot in configuration "bcfp" */
            State newstp;    /* A pointer to a successor state */

            /* Each configuration becomes complete after it contributes to a successor state.  Initially, all
            ** configurations are incomplete */
            for (cfp = stp.cfp; cfp != null; cfp = cfp.next) cfp.status = CfgStatus.INCOMPLETE;

            /* Loop through all configurations of the state "stp" */
            for (cfp = stp.cfp; cfp != null; cfp = cfp.next)
            {
                if (cfp.status == CfgStatus.COMPLETE) continue;    /* Already used by inner loop */
                if (cfp.dot >= cfp.rp.nrhs) continue;              /* Can't shift this config */
                ConfigList.Configlist_reset();                     /* Reset the new config set */
                sp = cfp.rp.rhs[cfp.dot];                          /* Symbol after the dot */

                /* For every configuration in the state "stp" which has the symbol "sp" following its dot, add the
                ** same configuration to the basis set under construction but with the dot shifted one symbol to
                ** the right. */
                for (bcfp = cfp; bcfp != null; bcfp = bcfp.next)
                {
                    if (bcfp.status == CfgStatus.COMPLETE) continue;    /* Already used */
                    if (bcfp.dot >= bcfp.rp.nrhs) continue;             /* Can't shift this one */
                    bsp = bcfp.rp.rhs[bcfp.dot];                        /* Get symbol after dot */
                    if (!same_symbol(bsp, sp)) continue;                /* Must be same as for "cfp" */
                    bcfp.status = CfgStatus.COMPLETE;                   /* Mark this config as used */
                    newcfg = ConfigList.Configlist_addbasis(bcfp.rp, bcfp.dot + 1);
                    newcfg.bplp = Plinks.Plink_add(newcfg.bplp, bcfp);
                }

                /* Get a pointer to the state described by the basis configuration set constructed in the preceding
                ** loop */
                newstp = getstate(lemp);

                /* The state "newstp" is reached from the state "stp" by a shift action on the symbol "sp" */
                if (sp.type == SymbolType.MULTITERMINAL)
                {
                    int i;
                    for (i = 0; i < sp.nsubsym; i++)
                    {
                        stp.ap = Actions.Action_add(stp.ap, ActionType.SHIFT, sp.subsym![i], newstp, null);
                    }
                }
                else
                {
                    stp.ap = Actions.Action_add(stp.ap, ActionType.SHIFT, sp, newstp, null);
                }
            }
        }

        /*
        ** Construct the propagation links
        */
        public static void FindLinks(Lemon lemp)
        {
            int i;
            Config? cfp;
            Config other;
            State? stp;
            Plink? plp;

            /* Housekeeping detail: Add to every propagate link a pointer back to the state to which the link is
            ** attached. */
            for (i = 0; i < lemp.nstate; i++)
            {
                stp = lemp.sorted[i];
                for (cfp = stp != null ? stp.cfp : null; cfp != null; cfp = cfp.next)
                {
                    cfp.stp = stp;
                }
            }

            /* Convert all backlinks into forward links.  Only the forward links are used in the follow-set
            ** computation. */
            for (i = 0; i < lemp.nstate; i++)
            {
                stp = lemp.sorted[i];
                for (cfp = stp != null ? stp.cfp : null; cfp != null; cfp = cfp.next)
                {
                    for (plp = cfp.bplp; plp != null; plp = plp.next)
                    {
                        other = plp.cfp;
                        other.fplp = Plinks.Plink_add(other.fplp, cfp);
                    }
                }
            }
        }

        /* Compute all followsets.
        **
        ** A followset is the set of all symbols which can come immediately after a configuration.
        */
        public static void FindFollowSets(Lemon lemp)
        {
            int i;
            Config? cfp;
            Plink? plp;
            bool progress;
            bool change;

            for (i = 0; i < lemp.nstate; i++)
            {
                System.Diagnostics.Debug.Assert(lemp.sorted[i] != null);
                for (cfp = lemp.sorted[i].cfp; cfp != null; cfp = cfp.next)
                {
                    cfp.status = CfgStatus.INCOMPLETE;
                }
            }

            do
            {
                progress = false;
                for (i = 0; i < lemp.nstate; i++)
                {
                    System.Diagnostics.Debug.Assert(lemp.sorted[i] != null);
                    for (cfp = lemp.sorted[i].cfp; cfp != null; cfp = cfp.next)
                    {
                        if (cfp.status == CfgStatus.COMPLETE) continue;
                        for (plp = cfp.fplp; plp != null; plp = plp.next)
                        {
                            change = Sets.SetUnion(plp.cfp.fws!, cfp.fws!);
                            if (change)
                            {
                                plp.cfp.status = CfgStatus.INCOMPLETE;
                                progress = true;
                            }
                        }
                        cfp.status = CfgStatus.COMPLETE;
                    }
                }
            } while (progress);
        }

        /* Compute the reduce actions, and resolve conflicts.
        */
        public static void FindActions(Lemon lemp)
        {
            int i, j;
            Config? cfp;
            State stp;
            Symbol? sp;
            Rule? rp;

            /* Add all of the reduce actions
            ** A reduce action is added for each element of the followset of a configuration which has its dot at
            ** the extreme right.
            */
            for (i = 0; i < lemp.nstate; i++)
            {   /* Loop over all states */
                stp = lemp.sorted[i];
                for (cfp = stp.cfp; cfp != null; cfp = cfp.next)
                {   /* Loop over all configurations */
                    if (cfp.rp.nrhs == cfp.dot)
                    {   /* Is dot at extreme right? */
                        for (j = 0; j < lemp.nterminal; j++)
                        {
                            if (Sets.SetFind(cfp.fws!, j))
                            {
                                /* Add a reduce action to the state "stp" which will reduce by the rule "cfp->rp" if
                                ** the lookahead symbol is "lemp->symbols[j]" */
                                stp.ap = Actions.Action_add(stp.ap, ActionType.REDUCE, lemp.symbols[j], null, cfp.rp);
                            }
                        }
                    }
                }
            }

            /* Add the accepting token */
            if (lemp.start != null)
            {
                sp = Tables.Symbol_find(lemp.start);
                if (sp == null)
                {
                    if (lemp.startRule == null)
                    {
                        System.Console.Error.Write("internal error on source line " + 387 + ": no start rule\n");
                        System.Environment.Exit(1);
                        return;
                    }
                    sp = lemp.startRule.lhs;
                }
            }
            else
            {
                sp = lemp.startRule!.lhs;
            }
            /* Add to the first state (which is always the starting state of the finite state machine) an action to
            ** ACCEPT if the lookahead is the start nonterminal.  */
            lemp.sorted[0].ap = Actions.Action_add(lemp.sorted[0].ap, ActionType.ACCEPT, sp, null, null);

            /* Resolve conflicts */
            for (i = 0; i < lemp.nstate; i++)
            {
                LemonAction? ap, nap;
                stp = lemp.sorted[i];
                /* assert( stp->ap ); */
                stp.ap = Actions.Action_sort(stp.ap);
                for (ap = stp.ap; ap != null && ap.next != null; ap = ap.next)
                {
                    for (nap = ap.next; nap != null && nap.sp == ap.sp; nap = nap.next)
                    {
                        /* The two actions "ap" and "nap" have the same lookahead.  Figure out which one should be
                        ** used */
                        lemp.nconflict += resolve_conflict(ap, nap);
                    }
                }
            }

            /* Report an error for each rule that can never be reduced. */
            for (rp = lemp.rule; rp != null; rp = rp.next) rp.canReduce = false;
            for (i = 0; i < lemp.nstate; i++)
            {
                LemonAction? ap;
                for (ap = lemp.sorted[i].ap; ap != null; ap = ap.next)
                {
                    if (ap.type == ActionType.REDUCE) ap.rp!.canReduce = true;
                }
            }
            for (rp = lemp.rule; rp != null; rp = rp.next)
            {
                if (rp.canReduce) continue;
                Errors.ErrorMsg(lemp.filename, rp.ruleline, "This rule can not be reduced.\n");
                lemp.errorcnt++;
            }
        }

        /* Resolve a conflict between the two given actions.  If the conflict can't be resolved, return non-zero.
        **
        ** NO LONGER TRUE:
        **   To resolve a conflict, first look to see if either action is on an error rule.  In that case, take the
        **   action which is not associated with the error rule.  If neither or both actions are associated with an
        **   error rule, then try to use precedence to resolve the conflict.
        **
        ** If either action is a SHIFT, then it must be apx.  This function won't work if apx->type==REDUCE and
        ** apy->type==SHIFT.
        */
        private static int resolve_conflict(LemonAction apx, LemonAction apy)
        {
            Symbol? spx, spy;
            int errcnt = 0;
            System.Diagnostics.Debug.Assert(apx.sp == apy.sp);  /* Otherwise there would be no conflict */
            if (apx.type == ActionType.SHIFT && apy.type == ActionType.SHIFT)
            {
                apy.type = ActionType.SSCONFLICT;
                errcnt++;
            }
            if (apx.type == ActionType.SHIFT && apy.type == ActionType.REDUCE)
            {
                spx = apx.sp;
                spy = apy.rp!.precsym;
                if (spy == null || spx.prec < 0 || spy.prec < 0)
                {
                    /* Not enough precedence information. */
                    apy.type = ActionType.SRCONFLICT;
                    errcnt++;
                }
                else if (spx.prec > spy.prec)
                {    /* higher precedence wins */
                    apy.type = ActionType.RD_RESOLVED;
                }
                else if (spx.prec < spy.prec)
                {
                    apx.type = ActionType.SH_RESOLVED;
                }
                else if (spx.prec == spy.prec && spx.assoc == Assoc.RIGHT)
                { /* Use operator */
                    apy.type = ActionType.RD_RESOLVED;                         /* associativity */
                }
                else if (spx.prec == spy.prec && spx.assoc == Assoc.LEFT)
                {  /* to break tie */
                    apx.type = ActionType.SH_RESOLVED;
                }
                else
                {
                    System.Diagnostics.Debug.Assert(spx.prec == spy.prec && spx.assoc == Assoc.NONE);
                    apx.type = ActionType.ERROR;
                }
            }
            else if (apx.type == ActionType.REDUCE && apy.type == ActionType.REDUCE)
            {
                spx = apx.rp!.precsym;
                spy = apy.rp!.precsym;
                if (spx == null || spy == null || spx.prec < 0 ||
                spy.prec < 0 || spx.prec == spy.prec)
                {
                    apy.type = ActionType.RRCONFLICT;
                    errcnt++;
                }
                else if (spx.prec > spy.prec)
                {
                    apy.type = ActionType.RD_RESOLVED;
                }
                else if (spx.prec < spy.prec)
                {
                    apx.type = ActionType.RD_RESOLVED;
                }
            }
            else
            {
                /* The REDUCE/SHIFT case cannot happen because SHIFTs come before REDUCEs on the list.  If we reach
                ** this point it must be because the parser conflict had already been resolved. */
            }
            return errcnt;
        }
    }
